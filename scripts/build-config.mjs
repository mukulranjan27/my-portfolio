import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Generates assets/js/config.js from environment variables (or .env when present)
 * for CI/CD platforms like Vercel, Netlify, and Cloudflare Pages.
 * If neither env var is provided, keeps existing assets/js/config.js intact.
 */
function loadDotEnv() {
  const envPath = resolve(process.cwd(), '.env');
  if (!existsSync(envPath)) return {};
  const parsed = {};
  for (const rawLine of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eqIndex = line.indexOf('=');
    if (eqIndex <= 0) continue;
    const key = line.slice(0, eqIndex).trim();
    const val = line.slice(eqIndex + 1).trim().replace(/^['"]|['"]$/g, '');
    parsed[key] = val;
  }
  return parsed;
}

const fileEnv = loadDotEnv();
const url = (process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL || fileEnv.SUPABASE_URL || '').trim();
const anonKey = (process.env.SUPABASE_ANON_KEY || process.env.VITE_SUPABASE_ANON_KEY || fileEnv.SUPABASE_ANON_KEY || '').trim();

if (!url && !anonKey) {
  console.log('[build-config] No SUPABASE_URL / SUPABASE_ANON_KEY env vars set; keeping existing assets/js/config.js.');
  process.exit(0);
}

if (!url || !anonKey) {
  console.error('[build-config] Error: Both SUPABASE_URL and SUPABASE_ANON_KEY must be provided together.');
  process.exit(1);
}

if (!url.startsWith('https://')) {
  console.error('[build-config] Error: SUPABASE_URL must start with https://');
  process.exit(1);
}

const output = `// Auto-generated by scripts/build-config.mjs. Only public client credentials belong here.
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)};
`;

writeFileSync(resolve(process.cwd(), 'assets/js/config.js'), output, 'utf8');
console.log('[build-config] Wrote assets/js/config.js from environment variables.');
